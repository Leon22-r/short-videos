WITH incoming AS (
  SELECT value AS row
  FROM jsonb_array_elements($1::jsonb)
  WHERE NULLIF(btrim(value->>'publish_id'), '') IS NOT NULL
)
INSERT INTO short_videos.publishing_jobs AS jobs (
  publish_id, publishing_backend, postiz_integration_id, approved_id, render_id, created_clip_id, niche, platform,
  channel_id, destination_id, youtube_channel_id, facebook_page_id,
  instagram_user_id, tiktok_open_id, credential_slot, meta_graph_version,
  instagram_graph_host, tiktok_domain_verified, tiktok_verified_url_prefix, default_privacy,
  requires_manual_publish, audit_status, tiktok_mode, video_source,
  video_file_id, video_url, public_video_url, local_file_path, title, caption, description,
  hashtags, scheduled_at, publish_status, retry_count, next_retry_at,
  last_error, post_id, post_url, started_at, completed_at, claimed_at,
  claimed_by, lease_expires_at, payload, created_at, updated_at
)
SELECT
  btrim(row->>'publish_id'),
  upper(COALESCE(NULLIF(btrim(row->>'publishing_backend'), ''), 'DIRECT')),
  COALESCE(btrim(row->>'postiz_integration_id'), ''),
  COALESCE(row->>'approved_id', ''),
  COALESCE(row->>'render_id', ''),
  COALESCE(row->>'created_clip_id', ''),
  COALESCE(row->>'niche', ''),
  upper(btrim(row->>'platform')),
  COALESCE(row->>'channel_id', ''),
  COALESCE(row->>'destination_id', ''),
  COALESCE(row->>'youtube_channel_id', ''),
  COALESCE(row->>'facebook_page_id', ''),
  COALESCE(row->>'instagram_user_id', ''),
  COALESCE(row->>'tiktok_open_id', ''),
  COALESCE(row->>'credential_slot', ''),
  COALESCE(row->>'meta_graph_version', ''),
  COALESCE(NULLIF(row->>'instagram_graph_host', ''), 'graph.facebook.com'),
  upper(COALESCE(row->>'tiktok_domain_verified', 'FALSE')) IN ('TRUE', '1', 'YES'),
  COALESCE(row->>'tiktok_verified_url_prefix', ''),
  COALESCE(NULLIF(row->>'default_privacy', ''), 'private'),
  upper(COALESCE(row->>'requires_manual_publish', 'FALSE')) IN ('TRUE', '1', 'YES'),
  COALESCE(row->>'audit_status', ''),
  COALESCE(NULLIF(row->>'tiktok_mode', ''), 'DIRECT'),
  COALESCE(row->>'video_source', ''),
  COALESCE(row->>'video_file_id', ''),
  COALESCE(row->>'video_url', ''),
  COALESCE(row->>'public_video_url', ''),
  COALESCE(row->>'local_file_path', ''),
  COALESCE(row->>'title', ''),
  COALESCE(row->>'caption', ''),
  COALESCE(row->>'description', ''),
  COALESCE(row->>'hashtags', ''),
  short_videos.safe_schedule_at(row->>'scheduled_at'),
  upper(COALESCE(NULLIF(row->>'publish_status', ''), 'PENDING')),
  GREATEST(COALESCE(NULLIF(row->>'retry_count', '')::integer, 0), 0),
  NULLIF(row->>'next_retry_at', '')::timestamptz,
  COALESCE(row->>'last_error', ''),
  COALESCE(row->>'post_id', ''),
  COALESCE(row->>'post_url', ''),
  NULLIF(row->>'started_at', '')::timestamptz,
  NULLIF(row->>'completed_at', '')::timestamptz,
  NULLIF(row->>'claimed_at', '')::timestamptz,
  COALESCE(row->>'claimed_by', ''),
  NULLIF(row->>'lease_expires_at', '')::timestamptz,
  row,
  COALESCE(NULLIF(row->>'created_at', '')::timestamptz, now()),
  COALESCE(NULLIF(row->>'updated_at', '')::timestamptz, now())
FROM incoming
ON CONFLICT (publish_id) DO UPDATE SET
  approved_id = EXCLUDED.approved_id,
  render_id = EXCLUDED.render_id,
  created_clip_id = EXCLUDED.created_clip_id,
  niche = EXCLUDED.niche,
  platform = EXCLUDED.platform,
  channel_id = EXCLUDED.channel_id,
  destination_id = EXCLUDED.destination_id,
  youtube_channel_id = EXCLUDED.youtube_channel_id,
  facebook_page_id = EXCLUDED.facebook_page_id,
  instagram_user_id = EXCLUDED.instagram_user_id,
  tiktok_open_id = EXCLUDED.tiktok_open_id,
  credential_slot = EXCLUDED.credential_slot,
  meta_graph_version = EXCLUDED.meta_graph_version,
  instagram_graph_host = EXCLUDED.instagram_graph_host,
  tiktok_domain_verified = EXCLUDED.tiktok_domain_verified,
  tiktok_verified_url_prefix = EXCLUDED.tiktok_verified_url_prefix,
  default_privacy = EXCLUDED.default_privacy,
  requires_manual_publish = EXCLUDED.requires_manual_publish,
  audit_status = EXCLUDED.audit_status,
  tiktok_mode = EXCLUDED.tiktok_mode,
  video_source = EXCLUDED.video_source,
  video_file_id = EXCLUDED.video_file_id,
  video_url = EXCLUDED.video_url,
  public_video_url = EXCLUDED.public_video_url,
  local_file_path = EXCLUDED.local_file_path,
  title = EXCLUDED.title,
  caption = EXCLUDED.caption,
  description = EXCLUDED.description,
  hashtags = EXCLUDED.hashtags,
  scheduled_at = EXCLUDED.scheduled_at,
  payload = jobs.payload || EXCLUDED.payload,
  updated_at = now()
WHERE NOT (jobs.publishing_backend = 'POSTIZ' AND (
  jobs.provider_stage <> '' OR jobs.started_at IS NOT NULL OR jobs.publish_status <> 'PENDING'
))
RETURNING *;
